// Turns a .glb file into a TypeScript module the 3D viewer can load offline.
//
//   npm run model                       -> embeds assets/models/headset.glb
//   npm run model -- path/to/other.glb  -> embeds another file
//
// The model is stored as a base64 data URI inside
// src/viewer/generated/headsetModel.ts, so the viewer works in Expo Go
// without a server and without internet at the pitch venue.
import { readFileSync, writeFileSync, mkdirSync, statSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const input = resolve(root, process.argv[2] ?? 'assets/models/headset.glb');
const output = resolve(root, 'src/viewer/generated/headsetModel.ts');

const bytes = readFileSync(input);
if (bytes.subarray(0, 4).toString('latin1') !== 'glTF') {
  console.error(`${input} is not a binary glTF (.glb) file.`);
  process.exit(1);
}

const sizeMb = statSync(input).size / (1024 * 1024);
if (sizeMb > 15) {
  console.warn(
    `Warning: the model is ${sizeMb.toFixed(1)} MB. Large models load slowly on phones. ` +
      'Try: npx @gltf-transform/cli optimize in.glb out.glb --compress quantize',
  );
}

mkdirSync(dirname(output), { recursive: true });
writeFileSync(
  output,
  '// Generated by scripts/embed-model.mjs. Do not edit by hand; run `npm run model` instead.\n' +
    `// Source: ${input.replace(root + '/', '')} (${(bytes.length / 1024).toFixed(0)} KB)\n` +
    `export const HEADSET_MODEL_URI =\n  'data:model/gltf-binary;base64,${bytes.toString('base64')}';\n`,
);
console.log(`Embedded ${input.replace(root + '/', '')} into ${output.replace(root + '/', '')}`);
